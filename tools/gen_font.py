"""Rasterize a pixel TrueType font at the sizes it is drawn on into firmware/gen/pixel_font.h, as gfx.c's
felucca_font_t: per glyph its advance, bitmap width and offset; 4 bits a pixel, 2 pixels a byte, rows padded to a
byte; 0 = off, 15 = on (no grey: the pixels of a pixel font are whole, and gfx.c blends only onto black).

  python3 tools/gen_font.py               (assets/fonts/PressStart2P-Regular.ttf -> firmware/gen/pixel_font.h)

The result is a Modified Version of the font under the SIL OFL 1.1, so it does not carry the font's Reserved Font
Name: in the firmware it is "Bytemania Pixel" (LICENSING.md)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets/fonts/PressStart2P-Regular.ttf"
OUT = ROOT / "firmware/gen/pixel_font.h"
FIRST, LAST = 32, 126
SIZES = [("FONT_P8", 8), ("FONT_P16", 16)]   # the font's own grid is 8 px: 8 is it, 16 each pixel doubled


def glyphs(size):
    font = ImageFont.truetype(str(SRC), size)
    ascent, descent = font.getmetrics()
    h = ascent + descent
    out = []
    for ch in range(FIRST, LAST + 1):
        adv = round(font.getlength(chr(ch)))
        im = Image.new("L", (adv, h), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"                          # whole pixels, no anti-aliasing
        d.text((0, 0), chr(ch), font=font, fill=255)
        px = im.load()
        data = []
        for y in range(h):
            row = [15 if px[x, y] >= 128 else 0 for x in range(adv)] + [0]
            data += [row[x] << 4 | row[x + 1] for x in range(0, adv, 2)]
        out.append((adv, data))
    return h, out


def c_array(name, ctype, values):
    lines = [", ".join(f"{v}" for v in values[i:i + 24]) for i in range(0, len(values), 24)]
    return f"static const {ctype} {name}[{len(values)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def main():
    text = ["/* Bytemania Pixel: generated by tools/gen_font.py from Press Start 2P (Copyright 2012 The Press Start 2P",
            " * Project Authors), rasterized. A Modified Version under the SIL Open Font License 1.1, not GPL: see",
            " * assets/fonts/PressStart2P-OFL.txt and LICENSING.md. ASCII 32..126. */",
            "#pragma once", "#include <stdint.h>", ""]
    for name, size in SIZES:
        h, gl = glyphs(size)
        off, data = [], []
        for adv, d in gl:
            off.append(len(data))
            data += d
        text.append(c_array(name + "_DATA", "uint8_t", data))
        text.append(c_array(name + "_ADV", "uint8_t", [adv for adv, _ in gl]))
        text.append(c_array(name + "_OFF", "uint16_t", off))
        text.append(f"static const felucca_font_t {name} = {{ {h}, 0, {FIRST}, {LAST}, {name}_ADV, {name}_ADV, "
                    f"{name}_OFF, {name}_DATA }};   /* {h} px high */\n")
    OUT.write_text("\n".join(text))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
